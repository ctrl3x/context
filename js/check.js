(function () {
  // катыш экрана «Проверять — значит видеть картину целиком» (sec-check):
  // приём тот же, что у чек-листа (js/checklist.js) и тёмного экрана
  // (js/decor.js) — скролл двигает границу проявления svg: видно всё, что
  // выше шарика, ниже скрыто; шарик катится строго по «хребту» check.svg
  // и не заходит на ответвления (горизонтали к «Уточнение меняет смысл»
  // влево и к «Проверка помогает…» вправо).
  //
  // Секция НЕ пинится, поэтому, как у тёмного экрана в js/decor.js, граница
  // привязана к пересечению вьюпорта: d = −832 — верх секции у нижней
  // кромки (шарик выглядывает из-под экрана «Не спешите верить заголовку…»),
  // дальше экран уезжает вверх. Скорость границы 2/3 px макета на 1px
  // скролла — как у соседних катыши: на экране шарик дрейфует вверх,
  // относительно секции спускается по хребту.
  //
  // Хребет кончается в воздухе (546.5;806 при высоте svg 818), поэтому на
  // последних 150px шарик растворяется на хвосте линии — как у чек-листа
  // у стыка с «Выводом»: висящая «бусина» на собранном экране выглядела
  // бы забытой (дальше скролл уводит секцию, шарить не о чем).
  const sec = document.querySelector('.sec-check');
  const svg = sec && sec.querySelector('.lines-svg');
  const ball = sec && sec.querySelector('.cl-ball');
  const pageInner = document.getElementById('page-inner');
  if (!sec || !svg || !ball || !pageInner) return;

  const H = 832;  // секция = один экран макета
  const FH = 818; // высота check.svg
  const SLOPE = 2 / 3; // скорость границы: px макета на 1px скролла
  const FADE = 150;    // длина растворения в конце, px хребта
  const LAST_Y = 806;  // конец хребта — хвост диагонали, не доходит до низа svg

  // «хребет» check.svg: вход из-под предыдущего экрана (верхняя кромка
  // секции, x=800.5), узлы-кружки (800;208) и (685;645), две диагонали,
  // хвост до (546.5;806). Вокруг кружков линии в макете подрезаны —
  // перемычки проходим по прямой «центр → конец отрезка»: чернила
  // отстают от кромки шарика максимум на 0.2px (субпиксель).
  const SPINE = [
    [800.5, 0], [800.5, 188], [800, 208],
    [786.5, 223], [607.5140308783829, 438.97285213099246], [595, 455],
    [603.4925755982906, 473.01868435279783], [675.5, 629],
    [685, 645], [672.5193465337494, 659.9536570152926], [546.5, 806]
  ];

  function pointAtY(y) {
    if (y <= SPINE[0][1]) return SPINE[0];
    for (let i = 1; i < SPINE.length; i++) {
      const a = SPINE[i - 1], b = SPINE[i];
      if (y <= b[1]) {
        // сегменты хребта всегда идут вниз — деление безопасно
        const t = (y - a[1]) / (b[1] - a[1]);
        return [a[0] + (b[0] - a[0]) * t, y];
      }
    }
    return SPINE[SPINE.length - 1];
  }

  function scale() { return pageInner.getBoundingClientRect().width / 1280; }

  function update() {
    const s = scale();
    if (s <= 0) return;
    // верх секции на странице в макетных пикселях (как pinTop в teardown.js)
    const top = (sec.getBoundingClientRect().top + window.scrollY) / s;
    // насколько секция поднялась по странице: −832 — верх у нижней кромки
    // вьюпорта, 0 — экран собран целиком, +832 — ушёл за верхнюю
    const d = window.scrollY / s - top;
    const b = Math.min(Math.max((d + H) * SLOPE, 0), LAST_Y);
    // clip-path инлайном, без var()/calc() — надёжнее в старых браузерах.
    // Пока js не выполнился, стиль отсутствует и svg полностью виден (фолбэк)
    svg.style.clipPath = 'inset(0px 0px ' + Math.max(FH - b, 0) + 'px 0px)';
    // шарик растворяется на последних FADE px хребта — хвост уходит в воздух
    ball.style.opacity = Math.min(Math.max((LAST_Y - b) / FADE, 0), 1);
    // в CSS у .cl-ball сдвиг на -10px (половина размера): в точку пути
    // попадает центр шарика
    const pt = pointAtY(b);
    ball.style.transform = 'translate(' + pt[0] + 'px, ' + pt[1] + 'px)';
  }

  window.addEventListener('scroll', update, { passive: true });
  window.addEventListener('resize', update);
  window.addEventListener('load', update);
  update();
})();
