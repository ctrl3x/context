(function () {
  // катыш двух соседних экранов: «Наука стала декорацией» (тёмный, белый
  // шарик) и «именно поэтому появляется решение» (светлый, чёрный шарик).
  // Приём тот же, что у чек-листа (js/checklist.js): скролл двигает границу
  // проявления svg — видно всё, что выше шарика, ниже скрыто; шарик катится
  // строго по «хребту» своего svg и не заходит на ответвления (горизонтали
  // к пиллам «#учёные доказали», «#вопросы», «##»).
  //
  // Секции ровно по одному экрану, поэтому привязать границу к прокрутке
  // самой секции (как в чек-листе) нельзя — она привязана к пересечению
  // вьюпорта: 0 — верх секции появляется из-под предыдущего экрана, дальше
  // секция уезжает за верхнюю кромку («парковки» на кромке, как в
  // чек-листе, тут нет).
  //
  // Граница ОДНА на оба экрана и едет со скоростью SLOPE = 2/3 px макета
  // на 1px скролла. Скорость подобрана так, чтобы шарик дошёл до нижней
  // кромки тёмного экрана ровно в момент, когда эта кромка на середине
  // вьюпорта (d = HANDOFF_D): стык виден, и обе половины кроссфейда
  // происходят на глазах. Точка стыка непрерывна: последний узел хребта
  // decor_dark.svg (583.5;832) совпадает с первым узлом finale_lines.svg
  // (583.5;0) — линия из макета переходит через границу секций без излома.
  //
  // НА СТЫКЕ шарик инвертирует цвет: белый гаснет на последних FADE px
  // хребта тёмного экрана, чёрный в это же время стоит на начале своего
  // хребта у стыка и разгорается — прозрачности меняются в противофазе
  // и в сумме дают ровно 1 (белый = (832−b)/150, чёрный = (b−682)/150),
  // поэтому визуально это один шарик, перекрашивающийся на границе.
  //
  // ХВОСТ ФИНАЛА — пин. После стыка хребет финала продолжает ехать на тех
  // же 2/3, но странице структурно хватает только на 2H − vh скролла
  // (два экрана по 832 минус запас вьюпорта), а хребту на этой скорости
  // нужно HANDOFF_D + FH/SLOPE = 1238. Раньше скорость чёрного шарика
  // подгонялась под фактический запас (K ≈ 1.2–1.3 при vh 800–832) — на
  // стыке шарик резко прибавлял и на экране ехал вниз вместо дрейфа
  // вверх. Теперь недостающий скролл добирает пин: его длину
  // PIN = HANDOFF_D + FH/SLOPE − (2H − vh) js выставляет высотой обёртки
  // .fin-pin (syncPin ниже); пока экран приколот transform'ом (как
  // td-pin/sci-pin, sticky нельзя), шарик спускается по хребту на стоячем
  // экране. Растворение начинается там же (последние FADE px хребта), но
  // кончается с запасом RESERVE — за ~120px скролла до последнего px
  // страницы: долиставший до упора пользователь шарика уже не видит, и
  // погрешности округления высоты пина его не вылавливают. Без JS обёртка
  // остаётся высотой 832 (пина нет), svg виден целиком — фолбэк статикой,
  // как и у остальных катыши.
  const secDecor = document.querySelector('.sec-decor');
  const secFinale = document.querySelector('.sec-finale');
  const svgDecor = secDecor && secDecor.querySelector('.lines-svg');
  const ballDecor = secDecor && secDecor.querySelector('.cl-ball');
  const svgFinale = secFinale && secFinale.querySelector('.lines-svg');
  const ballFinale = secFinale && secFinale.querySelector('.cl-ball');
  const wrapFinale = secFinale ? secFinale.parentElement : null; // .fin-pin
  const pageInner = document.getElementById('page-inner');
  if (!secDecor || !svgDecor || !ballDecor || !secFinale || !svgFinale || !ballFinale || !pageInner) return;

  const H = 832; // секция = один экран макета
  const FH = 548; // высота finale_lines.svg: экран 832, но хребет финала короче — кончается в воздухе над оранжевой линейкой (560)
  // Скорость границы: 2/3 px макета на 1px скролла. Секция поднимается
  // быстрее, чем шарик спускается по хребту, поэтому НА ЭКРАНЕ шарик
  // дрейфует вверх, но относительно секции движется по линии сверху вниз.
  const SLOPE = 2 / 3;
  const FADE = 150; // длина кроссфейда на стыке и растворения в конце, px хребта
  // Насколько раньше конца хребта шарик уже невидим: 80px хребта = 120px
  // скролла (80 / SLOPE). Запрос: долиставший до конца страницы пользователь
  // не должен видеть шарик — «ноль ровно в последнем px» слишком хрупок
  // (округление высоты пина, клампинг скролла). Хвост хребта после узла
  // (790;473) проявляется уже без шарика — линия и так кончается в воздухе.
  const RESERVE = 80;
  // d (прогресс прокрутки тёмного экрана), при котором граница доходит до
  // его нижней кромки: (d + H)·SLOPE = H → d = 416. В этот момент кромка
  // на середине вьюпорта (832 − 416), стык ровно в кадре.
  const HANDOFF_D = H / SLOPE - H;
  // Длина пина финала: хребет после стыка едет на тех же 2/3, и чтобы
  // шарик доехал до FH = 548 (растворение — на последних FADE px, но
  // с запасом RESERVE) ровно к последнему px скролла, страница должна
  // позволять докрутить до
  // d = HANDOFF_D + FH/SLOPE = 1238. Структурно же страница кончается на
  // d = 2H − vh (vh — высота вьюпорта в px макета; scale.js вписывает
  // экран 832px в высоту с запасом, а при заполнении ширины подрезает
  // его снизу — vh обычно 800–832). Разницу и добирает высота .fin-pin:
  // PIN = vh − 426, обычно 374–406px макета, пересчитывается на resize.

  // «хребет» decor_dark.svg: вход из-под «Вывода» (верхняя кромка секции),
  // узлы-кружки, выход за нижнюю кромку. Вокруг кружков линии в макете
  // подрезаны — перемычки проходим по прямой «центр → конец отрезка»,
  // тогда шарик (r=10) всегда накрывает чернила. Последняя диагональ
  // срезана сильнее всех (38.5px от узла (685;695) — этот «воздух» есть
  // и в статике), поэтому идём узел → её начало (661.3;725.3) → конец:
  // максимальный отрыв кромки шарика от чернил — 4px в этом зазоре.
  const SPINE_DECOR = [
    [826.5, 0], [826.5, 189], [826, 208], [814.5, 224],
    [607.4820180842096, 439.04837865818354], [595, 455],
    [603.5022957910014, 473.05237347941613], [678.5, 677],
    [685, 695], [661.3, 725.3], [583.5, 832]
  ];

  // «хребет» finale_lines.svg: входит из-под тёмного экрана (верхняя кромка
  // секции, x=583.5 — продолжение белой линии), узел-кружок (583;174),
  // диагональ к узлу (790;473), хвост до низа svg (790.5;548). Ответвления
  // (горизонтали к «##» и «в виде сервиса») не трогаем. Вокруг кружков
  // линии подрезаны — перемычки по прямой «центр → конец отрезка»: на
  // перемычке узел (583;174) → диагональ чернила отстают от кромки шарика
  // максимум на 0.2px (субпиксель), у узла (790;473) перемычка целиком
  // внутри кружка.
  const SPINE_FINALE = [
    [583.5, 0], [583.5, 154], [583, 174],
    [595.5342425193434, 190.0222564300385], [779.5, 456],
    [790, 473], [790.5, 493], [790.5, 548]
  ];

  function pointAtY(spine, y) {
    if (y <= spine[0][1]) return spine[0];
    for (let i = 1; i < spine.length; i++) {
      const a = spine[i - 1], b = spine[i];
      if (y <= b[1]) {
        // сегменты хребта всегда идут вниз — деление безопасно
        const t = (y - a[1]) / (b[1] - a[1]);
        return [a[0] + (b[0] - a[0]) * t, y];
      }
    }
    return spine[spine.length - 1];
  }

  function scale() { return pageInner.getBoundingClientRect().width / 1280; }

  // текущая длина пина финала, px макета; пересчитывается в syncPin()
  let pinLen = 0;

  // высота обёртки .fin-pin = экран 832 + пин PIN. Родительский #page свою
  // высоту пересчитывает только js/scale.js (по resize), поэтому после
  // смены высоты dispatch'им resize сами. Сравнение со старым значением —
  // защита от цикла: наш же resize-обработчик снова зовёт syncPin.
  function syncPin() {
    if (!wrapFinale) return;
    const s = scale();
    if (s <= 0) return;
    const vh = document.documentElement.clientHeight / s;
    pinLen = Math.max(HANDOFF_D + FH / SLOPE - (2 * H - vh), 0);
    // Единицы — px макета, БЕЗ множителя s: внутри #page-inner css-пиксель
    // и есть пиксель макета (масштабирует transform самого #page-inner),
    // высоты остальных пинов заданы так же (statement-pin 3532, td-pin
    // 4032). Множитель ·s сдвигал фактический конец страницы на
    // 1238·(s − 1): при s < 1 (узкие окна) страница кончалась раньше
    // хребта — шарик зависал у последнего экрана видимым; при s > 1 —
    // мёртвый хвост скролла и пустая полоса под секцией. Верно было только
    // при s = 1 (напр. окно 1280×800).
    const hpx = Math.round(H + pinLen);
    if (wrapFinale.style.height !== hpx + 'px') {
      wrapFinale.style.height = hpx + 'px';
      try { window.dispatchEvent(new Event('resize')); } catch (e) {}
    }
  }

  function update() {
    const s = scale();
    if (s <= 0) return;
    // верх секции на странице в макетных пикселях (как pinTop в teardown.js)
    const topD = (secDecor.getBoundingClientRect().top + window.scrollY) / s;
    // насколько тёмный экран поднялся по странице: −832 — верх у нижней
    // кромки вьюпорта, 0 — экран собран целиком, +832 — ушёл за верхнюю
    const d = window.scrollY / s - topD;

    // ---------- тёмный экран «Наука стала декорацией» ----------
    const b = Math.min(Math.max((d + H) * SLOPE, 0), H);
    // clip-path инлайном, без var()/calc() — надёжнее в старых браузерах.
    // Пока js не выполнился, стиль отсутствует и svg полностью виден (фолбэк)
    svgDecor.style.clipPath = 'inset(0px 0px ' + (H - b) + 'px 0px)';
    // в CSS у .cl-ball сдвиг на -10px (половина размера): в точку пути
    // попадает центр шарика
    const pd = pointAtY(SPINE_DECOR, b);
    ballDecor.style.transform = 'translate(' + pd[0] + 'px, ' + pd[1] + 'px)';
    // белый шарик гаснет на последних FADE px хребта — его подхватывает
    // чёрный шарик финала, их прозрачности в сумме дают 1 (см. шапку)
    ballDecor.style.opacity = Math.min(Math.max((H - b) / FADE, 0), 1);

    // ---------- пин финала ----------
    // экран доезжает до верхней кромки (d = H) и встаёт: шифт съедает
    // скролл один в один (в px макета, как у td-pin/sci-pin), чтобы хребет
    // успел доехать до конца на константных 2/3; после PIN·s секция
    // отпускается и доезжает вместе со страницей (в режиме заполнения
    // ширины vh < H — при отпускании открывается подрезанный низ)
    const shift = Math.min(Math.max(d - H, 0), pinLen);
    if (shift === 0) secFinale.style.transform = '';
    else secFinale.style.transform = 'translateY(' + shift + 'px)';

    // ---------- финал «именно поэтому появляется решение» ----------
    // Та же SLOPE, что у тёмного экрана, и линейный ход от стыка до конца
    // хребта. Формула одна и до, и во время пина: пока экран едет, шарик
    // на экране дрейфует вверх, как на всех катыши; в пине шифт съедает
    // скролл, и шарик спускается по хребту уже на стоячем экране — ровно
    // до FH на последнем px страницы (см. PIN в шапке).
    const bf = Math.min(Math.max((d - HANDOFF_D) * SLOPE, 0), FH);
    svgFinale.style.clipPath = 'inset(0px 0px ' + (FH - bf) + 'px 0px)';
    const pf = pointAtY(SPINE_FINALE, bf);
    ballFinale.style.transform = 'translate(' + pf[0] + 'px, ' + pf[1] + 'px)';
    // чёрный шарик разгорается В ПРОТИВОФАЗЕ белому: пока белый гаснет на
    // последних FADE px хребта декора (b от 682 до 832), чёрный стоит на
    // начале своего хребта у стыка и проявляется — сумма прозрачностей
    // ровно 1, выглядит как перекраска одного шарика у границы. Дальше
    // шарик растворяется: старт тот же (за FADE px до конца хребта,
    // bf = 398), но окно сжато до FADE − RESERVE и кончается на RESERVE px
    // раньше — шарик исчезает быстрее и не доживает до последнего экрана
    // (хребет тянется до 548 «в воздухе» над оранжевой линейкой, висящая
    // «бусина» в конце страницы выглядела бы забытой).
    const fadeIn = Math.min(Math.max((b - (H - FADE)) / FADE, 0), 1);
    const fadeOut = Math.min(Math.max((FH - RESERVE - bf) / (FADE - RESERVE), 0), 1);
    ballFinale.style.opacity = Math.min(fadeIn, fadeOut);
  }

  window.addEventListener('scroll', update, { passive: true });
  window.addEventListener('resize', function () { syncPin(); update(); });
  window.addEventListener('load', function () { syncPin(); update(); });
  syncPin();
  update();
})();

/* ============================================================
   Логотип-тикер финала «[КОНТЕКСТ]»: та же анимация, что у тикера
   чек-листа (js/checklist.js) — скролл только решает, когда лого в кадре
   (класс .in по IntersectionObserver), сам переход играют CSS-transition'ы
   фиксированной длительности. Отличие одно: буквы здесь — прямые
   флекс-элементы (space-between разводит их по строке), обёртки .ctx-word
   нет, поэтому «ширину слова» меряем как расстояние от правого края левой
   скобки до левого края правой — при снятом transform, иначе сомкнутая
   правая скобка исказит замер.
   ============================================================ */
(function () {
  const logo = document.querySelector('.giant-ctx');
  if (!logo) return;
  const pageInner = document.getElementById('page-inner');
  const brs = logo.querySelectorAll('.br');
  const brR = logo.querySelector('.br-r');
  // стартовый сдвиг правой скобки: наезжает на левую в сомкнутом состоянии.
  // Ширину меряем по факту и делим на scale страницы (getBoundingClientRect
  // даёт размер уже после transform: scale). Fallback 900px — на случай,
  // если скрипт не успел измерить шрифт
  function measure() {
    if (!pageInner || !brR || !brs.length) return;
    const s = pageInner.getBoundingClientRect().width / 1280;
    if (s <= 0) return;
    // подмену переменной и замер делаем без анимации и transform — иначе
    // при перемеривании после загрузки шрифта скобка «доедет» на пару
    // пикселей, а rect снялся бы со старым сдвигом. Всё в одном JS-такте,
    // поэтому промежуточных кадров браузер не рисует
    brs.forEach(function (b) { b.style.transition = 'none'; b.style.transform = 'none'; });
    const shift = (brR.getBoundingClientRect().left -
                   brs[0].getBoundingClientRect().right) / s;
    logo.style.setProperty('--ctx-shift', shift + 'px');
    void logo.offsetWidth; // форсируем reflow, чтобы новый сдвиг применился сразу
    brs.forEach(function (b) { b.style.transition = ''; b.style.transform = ''; });
  }
  measure();
  // после загрузки IBM Plex Mono ширина букв меняется — перемеряем
  if (document.fonts && document.fonts.ready) {
    document.fonts.ready.then(measure);
  }
  window.addEventListener('load', measure);
  window.addEventListener('resize', measure);

  // без IntersectionObserver (совсем старые браузеры) просто показываем
  // лого раскрытым — лучше статика, чем навсегда сомкнутые скобки
  if (!('IntersectionObserver' in window)) {
    logo.classList.add('in');
    return;
  }

  // пульс: пока лого в кадре, через паузу скобки схлопываются обратно
  // и снова раскрываются. Тайминги те же, что у тикера чек-листа.
  // Таймеры живут только пока финал виден — ушёл со скроллом, цикл
  // останавливается (иначе анимация гонялась бы впустую)
  const COLLAPSE = 1.4e3; // длительность «сжатия» + пауза сомкнутого состояния
  const PERIOD = 6.0e3;   // раз в сколько секунд повторяется пульс
  let loopT1 = null, loopT2 = null, reopenT = null, visible = false;

  function startLoop() {
    // первый пульс — после того, как доиграла стартовая анимация раскрытия
    loopT1 = setTimeout(function () {
      pulse();
      loopT2 = setInterval(pulse, PERIOD);
    }, 3.2e3);
  }
  function pulse() {
    // сжатие запускаем только если лого сейчас раскрыто
    if (!logo.classList.contains('in')) return;
    logo.classList.remove('in');
    clearTimeout(reopenT);
    reopenT = setTimeout(function () {
      // раскрываем обратно только если финал ещё на экране —
      // иначе «доигравший» таймер вруби раскрытие в скрытой секции
      if (visible) logo.classList.add('in');
    }, COLLAPSE);
  }
  function stopLoop() {
    clearTimeout(loopT1);
    clearInterval(loopT2);
    clearTimeout(reopenT);
    loopT1 = loopT2 = reopenT = null;
  }

  // два порога: лого активируется, когда больше чем на 60% в кадре;
  // сброс — только когда лого целиком ушло с экрана, чтобы анимация
  // переигрывалась при каждом возвращении, но не мигала на границе
  const io = new IntersectionObserver(function (entries) {
    for (let i = 0; i < entries.length; i++) {
      const e = entries[i];
      if (!e.isIntersecting) {
        visible = false;
        logo.classList.remove('in');
        stopLoop();
      } else if (e.intersectionRatio >= 0.6) {
        visible = true;
        logo.classList.add('in');
        if (!loopT1) startLoop();
      }
    }
  }, { threshold: [0, 0.6] });
  io.observe(logo);
})();
